#!/usr/bin/env python3
"""Rewrites the <script src> block at the end of index.html from js/manifest.json (run after adding a JS file)."""
import json, re, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = json.load(open(os.path.join(root, 'js/manifest.json')))['files']
p = os.path.join(root, 'index.html'); s = open(p, encoding='utf-8').read()
block = '<!-- APP-SCRIPTS:START (generated by tools/sync_index.py from js/manifest.json — do not edit by hand) -->\n' + '\n'.join(f'<script src="{f}"></script>' for f in files) + '\n<!-- APP-SCRIPTS:END -->'
if 'APP-SCRIPTS:START' in s: s = re.sub(r'<!-- APP-SCRIPTS:START.*?APP-SCRIPTS:END -->', lambda m: block, s, flags=re.S)
else: s = re.sub(r'<!-- Application scripts:.*?</script>\n(?=</body>)', lambda m: block + '\n', s, flags=re.S)
open(p, 'w', encoding='utf-8').write(s); print('index.html: %d scripts' % len(files))
